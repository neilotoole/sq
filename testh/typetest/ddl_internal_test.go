func TestDDLHeader(t *testing.T) {
	got := ddlHeader("TestFooDDL", "drivers/mysql", "MySQL 9")
	require.Contains(t, got, "-- Code generated by TestFooDDL; DO NOT EDIT.\n")
	require.Contains(t, got, " create for MySQL 9, ")
	require.Contains(t, got, "--   "+EnvUpdateDDL+"=1 go test -run '^TestFooDDL$' ./drivers/mysql/\n")

	got = ddlHeader("TestFooDDL", ".", "MySQL 9")
	require.Contains(t, got, " go test -run '^TestFooDDL$' ./\n", "a package at the module root")
}

func TestModuleRelDir(t *testing.T) {
	root := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(root, "go.mod"), []byte("module x\n"), 0o600))
	dir := filepath.Join(root, "a", "b")
	require.NoError(t, os.MkdirAll(dir, 0o750))

	got, err := moduleRelDir(dir)
	require.NoError(t, err)
	require.Equal(t, "a/b", got, "slash-separated, relative to the module root")

	got, err = moduleRelDir(root)
	require.NoError(t, err)
	require.Equal(t, ".", got)

	_, err = moduleRelDir(t.TempDir())
	require.Error(t, err, "no go.mod above the directory")
}

func TestEnvBool(t *testing.T) {
	const name = "SQ_TYPETEST_ENVBOOL_TEST"
	for val, want := range map[string]bool{"": false, "0": false, "false": false, "1": true, "true": true} {
		t.Setenv(name, val)
		got, err := envBool(name)
		require.NoError(t, err, "%q", val)
		require.Equal(t, want, got, "%q", val)
	}

	t.Setenv(name, "yes")
	_, err := envBool(name)
	require.Error(t, err, "a value that isn't a boolean is a mistake, not on or off")
	require.Contains(t, err.Error(), name)
}

// TestCheckDDLLoads_SingleConnPool runs the ddl subtest's load and checks on
// a pool of one connection (conn.max-open=1), a supported setting. The load
// uses a connection of its own, which must go back to the pool before the
// checks read through it, or they wait for it forever. The deadline turns
// that stall into a failure.
func TestCheckDDLLoads_SingleConnPool(t *testing.T) {
	th := testh.New(t)
	ctx, cancel := context.WithTimeout(th.Context, 30*time.Second)
	t.Cleanup(cancel) // Registered first, so it runs after the table drop.
	th.Context = ctx

	src := th.Source(sakila.Duck)
	src.Options = options.Options{driver.OptConnMaxOpen.Key(): 1}
	serverVer, err := th.Open(src).DBSemver(th.Context)
	require.NoError(t, err)

	cfg := Config{
		RowIDDecl: "INTEGER NOT NULL PRIMARY KEY",
		Cases:     []Case{NewCase("int", "INTEGER", int64(0), int64(7), "INTEGER", "INTEGER", kind.Int)},
	}
	cols, err := Resolve(cfg.Cases, serverVer)
	require.NoError(t, err)

	checkDDLLoads(t, th, src, cfg, func(s string) string { return s }, serverVer, cols)
}
